defmodule LedgerUI.Skill do
  @moduledoc """
  Builds the Claude Code skill that teaches an agent to write Ledger UI markup.

  Everything comes from the installed package (`LedgerUI.Docs`: `__components__/0`, module and
  function docs), so the skill describes exactly the version in `deps`. `SKILL.md` is a short index
  with the rules that hold for every component; `references/<component>.md` holds the attrs, slots
  and usage of one component, read only when that component is used. It needs nothing outside the
  compiled modules, so it works from a Hex package.

  `mix ledger_ui.install` writes it, `mix ledger_ui.gen.skill` refreshes it and the
  `:ledger_ui_skill` compiler refreshes it whenever the package version changes.
  """

  @marker "<!-- ledger_ui -->"
  @pointer """
  #{@marker}
  ## UI

  UI is Ledger UI. Load `.claude/skills/ledger-ui/SKILL.md` before writing or changing HEEx, and read
  the component's reference before using it. Regenerate it with `mix ledger_ui.gen.skill` after upgrading.
  """

  @doc "The default folder of the skill in a host app."
  @spec default_path() :: Path.t()
  def default_path, do: ".claude/skills/ledger-ui"

  @doc "The comment that marks the pointer block in `AGENTS.md` and `CLAUDE.md`."
  @spec marker() :: String.t()
  def marker, do: @marker

  @doc "The block `AGENTS.md` and `CLAUDE.md` carry to send an agent to the skill."
  @spec pointer() :: String.t()
  def pointer, do: @pointer

  @doc "The version of the installed package, which the generated `SKILL.md` carries in its heading."
  @spec version() :: String.t()
  def version do
    Application.load(:ledger_ui)
    :ledger_ui |> Application.spec(:vsn) |> to_string()
  end

  @doc "The version a skill folder was generated for, or `nil` when it has no `SKILL.md`."
  @spec installed_version(Path.t()) :: String.t() | nil
  def installed_version(path) do
    with {:ok, contents} <- File.read(Path.join(path, "SKILL.md")),
         [_, version] <- Regex.run(~r/^# LedgerUI (\S+)$/m, contents) do
      version
    else
      _ -> nil
    end
  end

  @doc "Writes the skill under `path`, replacing the references of a previous run."
  @spec write!(Path.t()) :: [{String.t(), String.t()}]
  def write!(path) do
    File.rm_rf!(Path.join(path, "references"))
    files = files()

    Enum.each(files, fn {relative, contents} ->
      file = Path.join(path, relative)
      File.mkdir_p!(Path.dirname(file))
      File.write!(file, contents)
    end)

    files
  end

  @doc "The files of the skill, as `{relative_path, contents}`."
  @spec files() :: [{String.t(), String.t()}]
  def files, do: files(LedgerUI.Docs.components(), version())

  @doc false
  @spec files([map()], String.t()) :: [{String.t(), String.t()}]
  def files(components, version),
    do: [{"SKILL.md", index(components, version)} | Enum.map(components, &reference/1)]

  defp index(components, version) do
    rows =
      Enum.map_join(components, "\n", fn c ->
        tags = Enum.map_join(c.functions, " ", &"`<.#{&1.name}>`")
        "| #{tags} | #{escape_cell(c.summary)} | [#{c.key}.md](references/#{c.key}.md) |"
      end)

    """
    ---
    name: ledger-ui
    description: >-
      Ledger UI #{version}: the Phoenix LiveView component library with the Ledger design
      (buttons, forms, inputs, tables, charts, modal, drawer, menus, tabs, app shell, toasts,
      icons and more). Use when writing or editing HEEx/LiveView markup or UI in this app, or a
      LiveView test that asserts on rendered UI. Read references/<component>.md before using
      a component: attrs and their allowed values are fixed, guessing them renders wrong markup.
    ---

    # LedgerUI #{version}

    Generated by `mix ledger_ui.gen.skill` from the installed package; it is refreshed when the
    package version changes (compiler `:ledger_ui_skill`). When this file and `deps/ledger_ui/lib`
    disagree, the source wins.

    ## Rules

    - Components are imported by `use LedgerUI` (in `html_helpers/0`). Never hand-write `lu-*`
      markup or classes for something a component covers; pass `class` to add to the root's classes.
    - Form controls take `field={@form[:name]}` (id, name, value and errors come from it) inside
      `<.form for={@form} phx-change="validate" phx-submit="save">`.
    - Overlays (modal, drawer, popover, menus, tooltip) need a stable `id`:
      `phx-click={LedgerUI.open("id")}`, `LedgerUI.close(socket, "id")` in `handle_event/3`,
      `LedgerUI.toggle(%JS{}, "id")` in a pipeline. They show with the class `open`; the server never
      renders that state by hand.
    - Events a component emits go to the LiveView, or to a LiveComponent with `phx-target={@myself}`.
      Long lists (tables, feeds) take `@streams.x`; do not keep more than a page in assigns.
    - Every component forwards unknown attributes (`id`, `phx-*`, `data-*`, `aria-*`) to its root.
    - Icons: `<.icon name="download" />`. The built-in names (`LedgerUI.Components.Icon.names/0`)
      work as they are. Any other Hugeicons Stroke Rounded icon is `<.icon name="huge-search-01" />`:
      write the name in full as a literal (never interpolated, so `mix ledger_ui.icons sync` finds
      it), then run `mix ledger_ui.icons sync` (or `get NAME`, `search TERM` to find names). It needs
      `config :ledger_ui, :icons_path, "priv/hugeicons"`. An unknown name renders nothing and logs a warning.
    - Theme: light by default; `data-theme="dark"` on `<html>` switches every component (the
      `theme_picker` component and the `lu-theme` localStorage key do it for the user). Use the
      design tokens (`var(--lu-ink)`, `var(--lu-accent)`...) for your own CSS, never fixed colors.
    - Setup: CSS `@import "tailwindcss"; @import "../../deps/ledger_ui/assets/css/ledger_ui.css";` (Tailwind v4 builds the components; no other stylesheet); JS
      `import {Hooks as LedgerHooks, DOM as LedgerDOM} from "ledger_ui"`, spread `LedgerHooks` into
      the `LiveSocket` `hooks` and call `LedgerDOM.onBeforeElUpdated(from, to)` from `dom.onBeforeElUpdated`.
      Components with client behaviour use hooks named `LedgerUI.<Name>`: do not rename their ids/data attributes.

    ## Components

    | Tags | What | Reference |
    |---|---|---|
    #{rows}
    """
  end

  defp reference(component) do
    body = Enum.map_join(component.functions, "\n\n", &function_section/1)

    {"references/#{component.key}.md",
     """
     # #{inspect(component.module)}

     #{component.moduledoc}

     #{body}
     """}
  end

  defp function_section(function) do
    """
    ## `<.#{function.name}>`

    #{function.doc}

    #{attrs_table(function.attrs)}
    #{global(function.global)}

    #{slots_list(function.slots)}
    """
    |> String.replace(~r/\n{3,}/, "\n\n")
    |> String.trim()
  end

  defp attrs_table([]), do: ""

  defp attrs_table(attrs) do
    rows = Enum.map_join(attrs, "\n", &attr_row/1)

    """
    | Attr | Type | Default | Values / notes |
    |---|---|---|---|
    #{rows}
    """
  end

  defp attr_row(attr) do
    "| `#{attr.name}`#{required(attr)} | `#{inspect(attr.type)}` | #{default(attr.opts)} | #{notes(attr)} |"
  end

  defp required(%{required: true}), do: " (required)"
  defp required(_attr), do: ""

  defp default(opts) do
    case Keyword.fetch(opts, :default) do
      {:ok, value} -> "`#{inspect(value) |> escape_cell()}`"
      :error -> ""
    end
  end

  defp notes(attr) do
    [values(attr.opts), attr.doc]
    |> Enum.reject(&(&1 in [nil, ""]))
    |> Enum.join(" - ")
    |> escape_cell()
  end

  defp values(opts) do
    case Keyword.fetch(opts, :values) do
      {:ok, values} -> Enum.map_join(values, ", ", &"`#{inspect_value(&1)}`")
      :error -> nil
    end
  end

  defp inspect_value(value) when is_binary(value), do: value
  defp inspect_value(value), do: inspect(value)

  defp escape_cell(text), do: text |> String.replace("\n", " ") |> String.replace("|", "\\|")

  defp global(nil), do: ""

  defp global(attr) do
    included = attr.opts |> Keyword.get(:include, []) |> Enum.map_join(", ", &"`#{&1}`")
    "Any other HTML/phx attribute goes to the root element#{extra(included)}."
  end

  defp extra(""), do: ""
  defp extra(included), do: ", including #{included}"

  defp slots_list([]), do: ""

  defp slots_list(slots) do
    "Slots:\n\n" <> Enum.map_join(slots, "\n", &slot_item/1)
  end

  defp slot_item(slot) do
    attrs = Enum.map_join(slot.attrs, ", ", &"`#{&1.name}`#{required(&1)}")

    ["- `<:#{slot.name}>`", required(slot), slot_attrs(attrs), slot_doc(slot.doc)]
    |> Enum.join()
  end

  defp slot_attrs(""), do: ""
  defp slot_attrs(attrs), do: " - attrs: " <> attrs

  defp slot_doc(nil), do: ""
  defp slot_doc(doc), do: " - " <> String.replace(doc, "\n", " ")
end
