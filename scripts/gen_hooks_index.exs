# Regenerates the imports and the Hooks map of priv/static/ledger_ui.esm.js (every hook) and rewrites
# priv/static/ledger_ui_core.esm.js (every hook except @heavy) from the files in priv/static/ledger_ui/hooks/
# (dropdown.js -> "LedgerUI.Dropdown"; my_hook.js -> "LedgerUI.MyHook").
#
# @heavy: hooks left out of "ledger_ui/core" (big, or pulling big libs, and rarely on a page); apps import them
# one by one: `import Chart from "ledger_ui/hooks/chart"`.
#
#     elixir scripts/gen_hooks_index.exs

heavy =
  ~w(ai_composer calendar chart code_block color_picker date_picker datetime_picker donut_chart flow
           image_input pixel_card sortable treeview
           line_chart phone_input signature_pad text_editor time_picker)

root = Path.expand("..", __DIR__)
entry = Path.join(root, "priv/static/ledger_ui.esm.js")
core = Path.join(root, "priv/static/ledger_ui_core.esm.js")

files =
  root
  |> Path.join("priv/static/ledger_ui/hooks/*.js")
  |> Path.wildcard()
  |> Enum.sort()

entries =
  for file <- files do
    base = Path.basename(file, ".js")
    camel = base |> String.split(["_", "-"], trim: true) |> Enum.map_join(&String.capitalize/1)
    {base, camel}
  end

render = fn entries ->
  imports =
    Enum.map_join(entries, "\n", fn {base, camel} ->
      ~s(import Hook#{camel} from "./ledger_ui/hooks/#{base}.js")
    end)

  map =
    Enum.map_join(entries, "\n", fn {_base, camel} ->
      ~s(  "LedgerUI.#{camel}": Hook#{camel},)
    end)

  {imports, map}
end

replace = fn src, tag, body ->
  re = ~r/(\/\/ GENERATED:#{tag}:START\n).*?(\/\/ GENERATED:#{tag}:END)/s
  Regex.replace(re, src, fn _, s, e -> s <> if(body == "", do: "", else: body <> "\n") <> e end)
end

{imports, map} = render.(entries)

entry
|> File.read!()
|> replace.("IMPORTS", imports)
|> replace.("HOOKS", map)
|> then(&File.write!(entry, &1))

core_entries = Enum.reject(entries, fn {base, _} -> base in heavy end)
{core_imports, core_map} = render.(core_entries)

File.write!(core, """
// GENERATED by `elixir scripts/gen_hooks_index.exs`: do not edit by hand.
// "ledger_ui/core": the common hooks and `DOM`, without the heavy ones (#{Enum.join(heavy, ", ")}).
//
//     import {Hooks, DOM, lazyHook} from "ledger_ui/core"
//     import Chart from "ledger_ui/hooks/chart"
//     const hooks = {...Hooks, "LedgerUI.Chart": Chart}

#{core_imports}

import {DOM} from "./ledger_ui/base.js"
import lazyHook from "./ledger_ui/lazy.js"

export const Hooks = {
#{core_map}
}

export {DOM, lazyHook}
export default {Hooks, DOM}
""")

IO.puts("#{length(entries)} hooks registered (#{length(core_entries)} in core)")
