# Generates lib/ledger_ui/components/table/layout.ex (python3 scripts/gen_table_layout.py): the container-query utilities of `Table`
# (columns that leave by priority, the two-line card layout), one literal class list per supported
# width (Tailwind only sees literal class names).
HIDE = [320, 360, 400, 420, 480, 520, 560, 600, 640, 680, 720, 760, 768, 800, 880, 960, 980, 1024, 1100, 1180, 1280]
CARD = [420, 480, 520, 560, 640, 720]

def q(w, cls):
    return " ".join(f"@max-[{w}px]:{c}" if not c.startswith("!") else f"@max-[{w}px]:{c}" for c in cls.split())

# splits on spaces that are not inside brackets/quotes: the classes below have no spaces ('_' is the space)
def card(w):
    P = lambda s: q(w, s)
    return {
        "thead": P("absolute size-px overflow-hidden [clip-path:inset(50%)] focus-within:static focus-within:block focus-within:h-auto focus-within:w-auto focus-within:overflow-visible focus-within:[clip-path:none] focus-within:px-3.5 focus-within:py-2"),
        "thead_tr": P("block"),
        "th": P("hidden"),
        "tbody": P("block"),
        "tr": P("grid grid-cols-[auto_minmax(0,1fr)_auto_auto] [grid-template-areas:'cb_head_status_act'_'cb_title_value_act'_'cb_keep_keep_act'] items-center border-b border-line px-3.5 py-2.5 last:border-b-0"),
        "td_base": P("min-w-0 max-w-none w-auto border-0 p-0"),
        "td_hidden": P("hidden"),
        "cb": P("block [grid-area:cb] pr-2.5"),
        "head": P("block [grid-area:head] font-mono text-[13px]"),
        "status": P("block [grid-area:status] justify-self-end"),
        "title": P("[display:-webkit-box] [grid-area:title] [-webkit-box-orient:vertical] [-webkit-line-clamp:2] [line-clamp:2] overflow-hidden whitespace-normal pr-2.5"),
        "title_wrap": P("block [grid-area:title] overflow-hidden whitespace-normal pr-2.5"),
        "value": P("block [grid-area:value] justify-self-end text-right"),
        "keep": P("block [grid-area:keep] pt-1"),
        "act": P("block [grid-area:act] pl-2.5 !w-auto"),
        "edit": P("block [grid-column:2/-1]"),
        "prow": P("hidden"),
        "sub_tr": P("block px-3.5 pt-0 pb-2.5"),
        "sub_td": P("block p-0"),
        "val": P("inline"),
    }

out = []
out.append('''defmodule LedgerUI.Components.Table.Layout do
  @moduledoc false
  # GENERATED by scripts/gen_table_layout.py: the container-query utilities of `LedgerUI.Components.Table`.
  # Tailwind only sees literal class names, so every supported width has its own literal list.
  # Regenerate with `python3 scripts/gen_table_layout.py`.

  @hide_widths %s
  @card_widths %s

  @hide %%{
''' % (HIDE, CARD))
out.append(",\n".join(f'    {w} => "@max-[{w}px]:hidden"' for w in HIDE))
out.append('''
  }

  # a panel item of a column that left: shown only once the column is hidden
  @show %{
''')
out.append(",\n".join(f'    {w} => "@max-[{w}px]:flex"' for w in HIDE))
out.append('''
  }

  @card %{
''')
blocks = []
for w in CARD:
    c = card(w)
    blocks.append(f"    {w} => %{{\n" + ",\n".join(f'      {k}: "{v}"' for k, v in c.items()) + "\n    }")
out.append(",\n".join(blocks))
out.append('''
  }

  @doc "The widths (px) a column priority may leave at."
  def hide_widths, do: @hide_widths

  @doc "The widths (px) the card layout may start at."
  def card_widths, do: @card_widths

  @doc "The class that hides a cell under `width` px of the table box."
  def hide(width), do: fetch!(@hide, width, @hide_widths, "breakpoints")

  @doc "The class that shows a panel item under `width` px (it is `hidden` otherwise)."
  def show(width), do: fetch!(@show, width, @hide_widths, "breakpoints")

  @doc "The class lists of the card layout that starts under `width` px (`card_below`)."
  def card(width), do: fetch!(@card, width, @card_widths, "card_below")

  defp fetch!(map, width, allowed, what) do
    case map do
      %{^width => value} ->
        value

      _ ->
        raise ArgumentError,
              "#{what} #{inspect(width)} is not supported: use one of #{inspect(allowed)} " <>
                "(Tailwind needs a literal class per width; see LedgerUI.Components.Table.Layout)"
    end
  end
end
''')
import os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
with open(os.path.join(root, "lib/ledger_ui/components/table/layout.ex"), "w") as f:
    f.write("".join(out))
