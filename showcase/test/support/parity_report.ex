defmodule LedgerShowcase.ParityReport do
  @moduledoc """
  Summary of the parity run (`print_summary/0`, printed after the suite) and the generator of
  `design/PARITY_STATUS.md` (`markdown/0`, written by `mix test --only parity_status`).
  """

  alias LedgerShowcase.{Canvas, Examples, Parity}

  @root Path.expand("../../..", __DIR__)
  @exceptions_file Path.expand("../parity_exceptions.exs", __DIR__)

  def exceptions, do: @exceptions_file |> Code.eval_file() |> elem(0)

  @doc "Rows `%{id, total, pass, fail, skipped, canvas, vitrine}` of the ids that ran."
  def rows do
    results = Map.new(Parity.results(), fn {k, src, st, first} -> {k, {src, st, first}} end)
    exc = exceptions()

    for id <- Examples.ids(),
        secs = Examples.sections(id),
        ran = Enum.filter(secs, &Map.has_key?(results, {id, &1.index})),
        ran != [] do
      st = fn s -> Enum.count(ran, &(elem(results[{id, &1.index}], 1) == s)) end
      src = fn s -> Enum.count(secs, &(Canvas.source(id, &1.index) == s)) end

      %{
        id: id,
        total: length(secs),
        pass: st.(:ok),
        fail: st.(:error),
        skipped: Enum.count(secs, &Map.has_key?(exc, {id, &1.index})),
        canvas: src.(:canvas),
        vitrine: src.(:vitrine)
      }
    end
  end

  def source_label(%{canvas: c, vitrine: 0}) when c > 0, do: "canvas"
  def source_label(%{canvas: 0}), do: "vitrine"
  def source_label(%{canvas: c, vitrine: v}), do: "canvas #{c} / vitrine #{v}"

  def print_summary do
    case rows() do
      [] ->
        :ok

      rows ->
        w = rows |> Enum.map(&String.length(&1.id)) |> Enum.max() |> max(2)

        lines =
          for r <- rows do
            "  #{String.pad_trailing(r.id, w)}  #{r.pass}/#{r.total}#{if r.skipped > 0, do: " (#{r.skipped} exc)", else: ""}  #{source_label(r)}"
          end

        total = Enum.sum_by(rows, & &1.total)
        pass = Enum.sum_by(rows, & &1.pass)
        canvas = Enum.sum_by(rows, & &1.canvas)
        vit = Enum.sum_by(rows, & &1.vitrine)

        IO.puts(
          "\nParity summary (id  passing/total  reference source)\n" <>
            Enum.join(lines, "\n") <>
            "\n  TOTAL: #{pass}/#{total} passing; references: #{canvas} canvas, #{vit} vitrine\n"
        )
    end
  end

  ## PARITY_STATUS.md

  @doc "API module (snake) owning each id, from `PARIDADE.md` + `docs.json`."
  def owners do
    names = @root |> Path.join("design/vitrine/docs.json") |> File.read!() |> Jason.decode!()
    by_name = Map.new(names, &{&1["name"], &1["id"]})

    @root
    |> Path.join("design/system/PARIDADE.md")
    |> File.read!()
    |> String.split("\n")
    |> Enum.flat_map(fn line ->
      case Regex.run(~r/^\| `([a-z_0-9]+)` \| ([^|]+) \|/, line) do
        [_, api, cards] ->
          for c <- String.split(cards, ","), id = by_name[String.trim(c)], do: {id, api}

        _ ->
          []
      end
    end)
    |> Map.new()
  end

  # PARIDADE.md does not list every card (e.g. Palette): fall back to a module named after the id.
  defp owner(owners, id) do
    snake = String.replace(id, "-", "_")

    cond do
      owners[id] -> owners[id]
      File.exists?(Path.join(@root, "lib/ledger_ui/components/#{snake}.ex")) -> snake
      true -> "unmapped"
    end
  end

  @doc "Example files that look like raw HTML copies (no `<.` component call, or a comment saying raw)."
  def raw_copies do
    for id <- Examples.ids(), %{index: i, source: src} <- Examples.sections(id), raw?(src) do
      {id, i}
    end
  end

  defp raw?(src) do
    not Regex.match?(~r/<\.[a-z_]+/, src) or Regex.match?(~r/<!--.*\braw\b/is, src) or
      Regex.match?(~r/<%!--.*\braw\b/is, src)
  end

  @doc "Markdown of the status (needs `Parity.results/0` of a FULL run)."
  def markdown do
    results = Map.new(Parity.results(), fn {k, src, st, first} -> {k, {src, st, first}} end)
    exc = exceptions()
    owners = owners()
    raws = raw_copies() |> Enum.group_by(&elem(&1, 0), &elem(&1, 1))

    per_id =
      for id <- Examples.ids() do
        secs = Examples.sections(id)

        failing =
          for s <- secs,
              {src, :error, first} <- [results[{id, s.index}]],
              do: {s.index, s.title, src, first}

        %{id: id, secs: secs, failing: failing, owner: owner(owners, id)}
      end

    total = Enum.sum_by(per_id, &length(&1.secs))
    nfail = Enum.sum_by(per_id, &length(&1.failing))
    canvas = Enum.count(Map.keys(results), fn {id, i} -> Canvas.source(id, i) == :canvas end)

    head = """
    # Parity status

    Generated by `cd showcase && mix test --only parity_status` (test `test/parity_status_test.exs`).
    Reference: the CANVAS (`design/canvas/G*Claro*.dc.html`) when it has the section, else the vitrine
    `sec/<id>.json`. Rule: the canvas is the source of truth. See `design/CANVAS_VS_VITRINE.md`.

    - Sections with an example: #{total}; failing: #{nfail}; with parity exception: #{map_size(exc)}
    - Reference resolved from the canvas: #{canvas}; vitrine fallback: #{map_size(results) - canvas}
    - Raw-copy example files (no `<.component>` call or "raw" comment): #{length(List.flatten(Map.values(raws)))}

    Work list for the next agents: fix the component (or its example) so each failing section passes,
    and convert raw-copy examples to real components where the component can produce the markup.

    """

    by_owner =
      per_id
      |> Enum.filter(&(&1.failing != [] or Map.has_key?(raws, &1.id)))
      |> Enum.group_by(& &1.owner)
      |> Enum.sort()
      |> Enum.map_join("\n", fn {owner, ids} ->
        "## `#{owner}` (lib/ledger_ui/components/#{owner}.ex)\n\n" <>
          Enum.map_join(ids, "\n", fn i -> id_block(i, raws[i.id] || []) end) <> "\n"
      end)

    summary =
      per_id
      |> Enum.group_by(& &1.owner)
      |> Enum.map(fn {owner, ids} ->
        {owner, Enum.sum_by(ids, &length(&1.failing)),
         Enum.sum_by(ids, &length(raws[&1.id] || [])), Enum.sum_by(ids, &length(&1.secs))}
      end)
      |> Enum.filter(fn {_, f, r, _} -> f > 0 or r > 0 end)
      |> Enum.sort()
      |> Enum.map_join("\n", fn {o, f, r, t} -> "| `#{o}` | #{f} | #{r} | #{t} |" end)

    exceptions_md =
      exc
      |> Enum.sort()
      |> Enum.map_join("\n", fn {{id, i}, why} -> "- #{id} #{pad(i)}: #{why}" end)

    head <>
      "## Summary per module owner\n\n| module | failing sections | raw-copy examples | sections |\n|---|---|---|---|\n" <>
      summary <>
      "\n\n## Parity exceptions (`test/parity_exceptions.exs`)\n\n" <>
      exceptions_md <> "\n\n# Work list\n\n" <> by_owner <> "\n"
  end

  defp id_block(i, raws) do
    fails =
      Enum.map_join(i.failing, "\n", fn {idx, title, src, first} ->
        "  - #{pad(idx)} (#{title}) [vs #{src}]: `#{oneline(first)}`"
      end)

    raw =
      if raws == [],
        do: "",
        else:
          "\n  - raw-copy examples (#{length(raws)}/#{length(i.secs)}): #{Enum.map_join(raws, ", ", &pad/1)}"

    "- **#{i.id}**: #{length(i.failing)}/#{length(i.secs)} failing" <>
      if(fails == "", do: "", else: "\n" <> fails) <> raw
  end

  defp pad(i), do: i |> Integer.to_string() |> String.pad_leading(2, "0")

  defp oneline(s),
    do: s |> String.replace(~r/\s+/, " ") |> String.replace("`", "'") |> String.slice(0, 300)
end
