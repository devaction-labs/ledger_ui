defmodule LedgerUI.ReadmeExamplesTest do
  @moduledoc """
  Every ```heex block of the README (the install snippet, the "Tema" examples and one example per
  component) must compile against the library: no unknown component, attr or slot and no value outside `values:`.
  (`missing required` is ignored: the examples are short.) The component section is generated by
  `mix run scripts/gen_readme_components.exs`.
  """
  use ExUnit.Case, async: true

  @readme Path.expand("../README.md", __DIR__)
  @external_resource @readme

  @blocks (for {[_, code], i} <-
                 @readme
                 |> File.read!()
                 |> then(&Regex.scan(~r/```heex\n(.*?)```/s, &1))
                 |> Enum.with_index(1) do
             {i, code}
           end)

  test "the README has an example per component" do
    components =
      for m <- LedgerUI.Components.__modules__(),
          {name, _} <- m.__components__(),
          function_exported?(m, name, 1),
          do: name

    readme = File.read!(@readme)

    missing = for n <- components, not String.contains?(readme, "`<.#{n}>`"), do: n
    assert missing == [], "components without an example in the README: #{inspect(missing)}"
    assert length(@blocks) >= length(components)
  end

  for {i, code} <- @blocks do
    test "README heex block ##{i} compiles" do
      code = unquote(code)

      assert LedgerUI.ReadmeCheck.check(code, "#{unquote(i)}") == :ok,
             "README block ##{unquote(i)} does not compile:\n#{code}"
    end
  end
end
