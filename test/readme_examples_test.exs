defmodule LedgerUI.ReadmeExamplesTest do
  @moduledoc """
  Every ```heex block of the README (the install snippet, the "Tema" examples and one example per
  component) must compile against the library with no warning at all: no unknown component, attr or slot, no value
  outside `values:` and no `missing required` (the generator fills the `id` and the other required attrs and slots).
  The component section is generated by `mix run scripts/gen_readme_components.exs`.
  """
  use ExUnit.Case, async: true

  @readme Path.expand("../README.md", __DIR__)
  @external_resource @readme

  @blocks (for {[_, code], i} <-
                 @readme
                 |> File.read!()
                 |> then(&Regex.scan(~r/```heex\n(.*?)```/s, &1))
                 |> Enum.with_index(1) do
             {i, code}
           end)

  test "the README has an example per component" do
    components =
      for m <- LedgerUI.Components.__modules__(),
          {name, _} <- m.__components__(),
          function_exported?(m, name, 1),
          do: name

    readme = File.read!(@readme)

    missing = for n <- components, not String.contains?(readme, "`<.#{n}>`"), do: n
    assert missing == [], "components without an example in the README: #{inspect(missing)}"
    assert length(@blocks) >= length(components)
  end

  test "the README has the requirements, the RTL note and the guides" do
    readme = File.read!(@readme)

    assert readme =~ "## Requisitos"
    assert readme =~ "1.2.13"
    assert readme =~ "RTL não é suportado"
    assert readme =~ "defer_items"
    assert readme =~ "**Embrulhando um componente.**"
    assert readme =~ "`live_session`"
  end

  test "no README link points to a file that is not in the Hex package" do
    in_package =
      ~w(lib priv assets guides mix.exs package.json README.md LICENSE CHANGELOG.md UPGRADING.md)

    links =
      for [_, target] <- Regex.scan(~r/\]\(([^)\s]+)\)/, File.read!(@readme)),
          not String.starts_with?(target, ["http://", "https://", "#", "mailto:"]),
          do: target |> String.split("#") |> hd()

    outside =
      for l <- Enum.uniq(links),
          l != "",
          top = l |> Path.split() |> hd(),
          top not in in_package,
          do: l

    assert outside == [], "README links to files outside the Hex package: #{inspect(outside)}"

    for l <- Enum.uniq(links), l != "" do
      assert File.exists?(Path.expand(l, Path.dirname(@readme))),
             "README links to a missing file: #{l}"
    end
  end

  for {i, code} <- @blocks do
    test "README heex block ##{i} compiles" do
      code = unquote(code)

      assert LedgerUI.ReadmeCheck.check(code, "#{unquote(i)}") == :ok,
             "README block ##{unquote(i)} does not compile:\n#{code}"
    end
  end
end
